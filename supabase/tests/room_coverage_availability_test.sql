  exception when others then if sqlerrm like 'FAIL:%' then raise; end if; end;
  reset role;
  perform set_config('request.jwt.claims',json_build_object('sub',person,'role','authenticated')::text,true);
  set local role authenticated;
  begin perform public.set_planned_shift_break(shift_id,'15:00','15:30'); raise exception 'FAIL: educator edited break plan';
  exception when others then if sqlerrm like 'FAIL:%' then raise; end if; end;
end $$;

    values(center,other_room,'Rollback unknown','Demand',current_date);
  set local role authenticated;
  select * into x from public.get_coverage_candidates(room,day,'14:00','15:00') where profile_id=person;
  if x.available or x.reason not like 'Source-room forecast cannot safely lend%' then raise exception 'FAIL: conflicting published shift with unknown demand ignored'; end if;
  reset role;
  update public.staff_shifts set classroom_id=null where id=shift_id;
  insert into public.staff_time_off_requests(daycare_id,staff_member_id,starts_on,ends_on,kind,status) values(center,member,day,day,'vacation','approved');
  set local role authenticated;

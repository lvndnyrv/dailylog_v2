  perform public.set_planned_shift_break(shift_id,'12:00','12:30');
  select * into x from public.get_coverage_candidates(room,day,'12:00','14:00') where profile_id=person;
  if x.available or x.reason not like '%break%' then raise exception 'FAIL: planned break ignored'; end if;
  select * into x from public.get_coverage_candidates(room,day,'12:30','14:00') where profile_id=person;
  if not x.available or x.needs_confirmation then raise exception 'FAIL: available post-break interval not offered'; end if;
  cover:=public.assign_planned_room_coverage(person,room,day,'12:30','14:00');
  begin perform public.set_planned_shift_break(shift_id,'13:00','13:30'); raise exception 'FAIL: break overwrote coverage';
  exception when others then if sqlerrm like 'FAIL:%' then raise; end if; end;
  begin perform public.set_planned_shift_break(shift_id,'06:00','06:30'); raise exception 'FAIL: out-of-shift break accepted';
  exception when check_violation then null; end;

  day date:=current_date+30; a timestamptz; b timestamptz; x record;
begin
  update public.daycares set timezone='America/Toronto',opens_at='06:30',closes_at='19:30' where id=center;
  delete from public.center_closures where daycare_id=center;
  insert into public.classrooms(daycare_id,name,capacity,ratio_children_per_educator) values(center,'Rollback availability',12,4) returning id into room;
  insert into public.classrooms(daycare_id,name,capacity,ratio_children_per_educator) values(center,'Rollback other room',12,4) returning id into other_room;
  insert into auth.users(id,instance_id,aud,role,email,encrypted_password,email_confirmed_at,raw_app_meta_data,raw_user_meta_data,created_at,updated_at)
    values(person,'00000000-0000-0000-0000-000000000000','authenticated','authenticated','coverage-test-'||person||'@dailylog.invalid','',now(),'{"provider":"email","providers":["email"]}','{"full_name":"Rollback coverage candidate"}',now(),now());

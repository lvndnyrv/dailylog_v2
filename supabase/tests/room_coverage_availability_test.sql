  exception when check_violation then null; end;
  reset role;
  delete from public.staff_time_off_requests where staff_member_id=member;
  update public.profiles set classroom_id=other_room where id=person;
  set local role authenticated;
  select * into x from public.get_coverage_candidates(room,day,'14:00','15:00') where profile_id=person;
  if x.available or x.reason not like 'Source-room forecast cannot safely lend%' then raise exception 'FAIL: home-room educator was treated as spare'; end if;
  reset role;
  update public.profiles set classroom_id=null where id=person;
  update public.staff_members set background_check_required=true where id=member;
  set local role authenticated;
  select * into x from public.get_coverage_candidates(room,day,'14:00','15:00') where profile_id=person;
  if x.available then raise exception 'FAIL: pending clearance offered'; end if;
  reset role;
  update public.staff_members set background_check_required=false where id=member;
  set local role authenticated;
  begin perform public.assign_planned_room_coverage(person,room,day,'06:00','07:00',true); raise exception 'FAIL: outside center hours accepted';
  exception when others then if sqlerrm like 'FAIL:%' then raise; end if; end;
  reset role;
  insert into public.center_closures(daycare_id,starts_on,ends_on,reason) values(center,day,day,'Rollback closure');

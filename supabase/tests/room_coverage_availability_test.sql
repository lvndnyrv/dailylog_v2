  if x.available then raise exception 'FAIL: overlapping coverage offered'; end if;
  select * into x from public.get_coverage_candidates(room,day,'14:00','15:00') where profile_id=person;
  if not x.available then raise exception 'FAIL: adjacent coverage blocked'; end if;

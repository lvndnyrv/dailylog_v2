  if not x.available or not x.needs_confirmation then raise exception 'FAIL: missing shift was advertised as confirmed'; end if;
  begin perform public.assign_planned_room_coverage(person,room,day,'12:00','14:00'); raise exception 'FAIL: unscheduled coverage skipped confirmation';
